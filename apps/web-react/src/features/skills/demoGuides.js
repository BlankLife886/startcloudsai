export function createDemoSkillRun(skill, request = "") {
  const guide = DEMO_SKILL_GUIDES[skill?.id];
  if (!guide) throw new Error("请选择一个演示 Skill");

  const requestText = String(request ?? "");
  const example = guide.examples.find((item) => item.request === requestText);
  const values = example
    ? { ...example.values }
    : Object.fromEntries(
        skill.fields.map((field) => [
          field.key,
          field.type === "select" ? field.options?.[0] || "" : "",
        ]),
      );

  if (!example) {
    if (skill.id === "brand-copy") {
      values.brand = "你的品牌";
      values.context = requestText;
    } else {
      const textField = skill.fields.find((field) => field.type !== "select");
      if (textField) values[textField.key] = requestText;
    }
  }

  const result = buildDemoSkillResult(skill, values);
  return {
    ...result,
    request: requestText,
    appliedRules: guide.rules.map((rule) => rule.title),
  };
}
